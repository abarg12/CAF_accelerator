"""Write twiddles.h, the FFT twiddle factor ROM for the optimized CAF.

    python gen_twiddles.py

The table holds W^k = exp(-2j*pi*k/N) for k = 0 .. N/2 - 1, rounded to single
precision. Rerun this if LOG2_NUM_OF_SAMPLES in caf.h changes.
"""

import math
from pathlib import Path

LOG2_NUM_OF_SAMPLES = 8
N = 1 << LOG2_NUM_OF_SAMPLES


def table(name, values):
    lines = [f"static const DTYPE {name}[NUM_OF_SAMPLES / 2] = {{"]
    for start in range(0, len(values), 4):
        row = ", ".join(f"{v: .9e}f" for v in values[start:start + 4])
        lines.append(f"    {row},")
    lines.append("};")
    return "\n".join(lines)


angles = [-2 * math.pi * k / N for k in range(N // 2)]
header = f"""/*
 * FFT twiddle factors W^k = exp(-2j*pi*k/N), k = 0 .. N/2 - 1, for N = {N}.
 * Generated by gen_twiddles.py. Do not edit by hand.
 */

#ifndef TWIDDLES_H_
#define TWIDDLES_H_

#include "caf.h"

#if NUM_OF_SAMPLES != {N}
#error "twiddles.h was generated for a different FFT size; rerun gen_twiddles.py"
#endif

{table("twiddle_real", [math.cos(a) for a in angles])}

{table("twiddle_imag", [math.sin(a) for a in angles])}

#endif
"""

Path(__file__).with_name("twiddles.h").write_text(header)
